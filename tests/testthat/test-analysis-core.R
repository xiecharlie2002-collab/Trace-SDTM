test_that("表格由同一结果对象输出 CSV、HTML 和 RTF", {
  skip_if_not_installed("admiral", minimum_version = "1.5.0")
  skip_if_not_installed("r2rtf", minimum_version = "1.3.1")
  plan <- load_analysis_plan()
  sdtm <- demo_sdtm_datasets()
  adsl <- derive_adsl(sdtm$DM, plan)
  adae <- derive_adae(sdtm$AE, adsl, plan)
  config <- demo_analysis_config(file.path(tempdir(), paste0("trace-tlf-", sample.int(1e8, 1L))))
  ensure_output_directories(config)
  objects <- list(
    `T14.1.1` = demographic_table_object(adsl, plan),
    `T14.3.1` = teae_table_object(adsl, adae, plan)
  )
  manifest <- purrr::map_dfr(objects, write_table_object, config = config)
  expect_equal(nrow(manifest), 2L)
  paths <- unlist(manifest[c("csv_path", "html_path", "rtf_path")], use.names = FALSE)
  expect_true(all(file.exists(paths)))
  expect_true(all(file.info(paths)$size > 0L))
  issues <- table_validation_issues(objects, list(ADSL = adsl, ADAE = adae), config)
  expect_equal(nrow(issues), 0L)
})

test_that("ADaM CSV 与 XPT 可以回读且结构保持一致", {
  skip_if_not_installed("admiral", minimum_version = "1.5.0")
  plan <- load_analysis_plan()
  sdtm <- demo_sdtm_datasets()
  datasets <- list(ADSL = derive_adsl(sdtm$DM, plan))
  datasets$ADAE <- derive_adae(sdtm$AE, datasets$ADSL, plan)
  config <- demo_analysis_config(file.path(tempdir(), paste0("trace-adam-", sample.int(1e8, 1L))))
  ensure_output_directories(config)
  manifest <- purrr::imap_dfr(datasets, ~ write_adam_dataset(.x, .y, plan, config))
  reread <- load_adam_datasets(config)
  expect_equal(nrow(manifest), 2L)
  expect_identical(names(reread$ADSL), analysis_variable_names(plan, "ADSL"))
  expect_identical(names(reread$ADAE), analysis_variable_names(plan, "ADAE"))
  expect_s3_class(reread$ADSL$TRTSDT, "Date")
  expect_equal(nrow(validate_adam_datasets(reread, sdtm, plan)), 0L)
})

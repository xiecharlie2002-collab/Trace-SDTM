test_that("ADSL 与 ADAE 按冻结规则派生并通过本地检查", {
  skip_if_not_installed("admiral", minimum_version = "1.5.0")
  plan <- load_analysis_plan()
  sdtm <- demo_sdtm_datasets()
  adsl <- derive_adsl(sdtm$DM, plan)
  adae <- derive_adae(sdtm$AE, adsl, plan)
  expect_equal(dim(adsl), c(6L, 19L))
  expect_equal(nrow(adae), 9L)
  expect_equal(sum(adae$TRTEMFL == "Y", na.rm = TRUE), 7L)
  expect_equal(sum(is.na(adae$TRTEMFL)), 2L)
  expect_equal(dplyr::n_distinct(adae$USUBJID[!is.na(adae$TRTEMFL) & adae$TRTEMFL == "Y"]), 5L)
  expect_equal(nrow(validate_adam_datasets(list(ADSL = adsl, ADAE = adae), sdtm, plan)), 0L)
})

